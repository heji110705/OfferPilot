  /* ---------------- 派生工具 ---------------- */

  var TYPE_NAME = { campus: '校招', intern: '实习' };

  function deadlineOf(job, now) {
    if (job.deadline) return job.deadline;
    /* 手动导入的岗位通常没有「剩余天数」，按长期招聘处理 */
    if (!Number.isFinite(job.days)) return '';
    var t = new Date(now || Date.now());
    t.setDate(t.getDate() + job.days);
    return t.toISOString().slice(0, 10);
  }

  function daysLeft(job, now) {
    var d = deadlineOf(job, now);
    if (!d) return null;
    var end = new Date(d + 'T23:59:59');
    return Math.ceil((end - new Date(now || Date.now())) / 86400000);
  }

  /* 把岗位补全成视图直接可用的结构（截止日期、类型名、剩余天数） */
  function decorate(job, now) {
    var out = {};
    Object.keys(job).forEach(function (k) { out[k] = job[k]; });
    out.deadline = deadlineOf(job, now);
    out.daysLeft = daysLeft(job, now);
    out.typeName = TYPE_NAME[job.type] || job.type;
    out.closed = out.daysLeft != null && out.daysLeft < 0;
    out.text = [job.company, job.role, job.city, job.industry, (job.tags || []).join(' '),
      job.summary, (job.duty || []).join(' '), (job.req || []).join(' ')].join(' ');
    return out;
  }

  function all(now) {
    return RAW.map(function (j) { return decorate(j, now); });
  }

  function uniq(list) {
    var seen = {}, out = [];
    list.forEach(function (x) { if (x && !seen[x]) { seen[x] = 1; out.push(x); } });
    return out;
  }

  var INDUSTRIES = uniq(RAW.map(function (j) { return j.industry; }));
