  /* 筛选 + 排序（纯函数，便于测试）：filter {q,type,city,industry,degree,onlyOpen,savedIds} */
  function query(list, filter, sort) {
    filter = filter || {};
    var q = (filter.q || '').trim().toLowerCase();
    var out = (list || []).filter(function (j) {
      if (filter.type && filter.type !== 'all' && j.type !== filter.type) return false;
      if (filter.city && filter.city !== 'all' && j.city !== filter.city) return false;
      if (filter.industry && filter.industry !== 'all' && j.industry !== filter.industry) return false;
      if (filter.degree && filter.degree !== 'all' && j.degree !== filter.degree) return false;
      if (filter.onlyOpen && j.closed) return false;
      if (filter.savedIds && !j.savedIds) return false;
      if (q) {
        var hay = (j.text || (j.company + j.role + j.city + j.industry + (j.tags || []).join(' '))).toLowerCase();
        if (hay.indexOf(q) < 0) return false;
      }
      return true;
    });
    var by = sort || 'match';
    out.sort(function (a, b) {
      if (by === 'deadline') {
        var da = a.daysLeft == null ? 9999 : a.daysLeft;
        var db = b.daysLeft == null ? 9999 : b.daysLeft;
        if (da !== db) return da - db;
      } else if (by === 'new') {
        return (b.fresh || 0) - (a.fresh || 0);
      } else {
        var ma = a.match == null ? -1 : a.match;
        var mb = b.match == null ? -1 : b.match;
        if (mb !== ma) return mb - ma;
      }
      return (b.match || 0) - (a.match || 0);
    });
    return out;
  }

  /* 岗位情报：按行业 / 城市聚合，供「情报」页与工作台使用 */
  function group(list, key) {
    var map = {};
    (list || []).forEach(function (j) {
      var k = j[key] || '其他';
      map[k] = map[k] || { key: k, total: 0, campus: 0, intern: 0, soon: 0 };
      map[k].total++;
      if (j.type === 'intern') map[k].intern++; else map[k].campus++;
      if (j.daysLeft != null && j.daysLeft >= 0 && j.daysLeft <= 7) map[k].soon++;
    });
    return Object.keys(map).map(function (k) { return map[k]; })
      .sort(function (a, b) { return b.total - a.total; });
  }

  /* 从一段粘贴的 JD 里猜企业 / 岗位 / 城市，用于「粘贴链接快速建任务」 */
  function guess(text) {
    var t = String(text || '').replace(/\s+/g, ' ').trim();
    var company = (t.match(/【([^】]{2,14})】/) || [])[1]
      || (t.match(/^([\u4e00-\u9fa5A-Za-z]{2,14})(?:公司|集团|科技|银行|证券)/) || [])[1]
      || '';
    var role = (t.match(/(招聘|岗位|职位)[:：]\s*([^\s，,。]{2,18})/) || [])[2]
      || (t.match(/([\u4e00-\u9fa5]{2,12}(?:工程师|分析师|经理|策划|运营|设计师|管培生|实习生|顾问|研究员))/) || [])[1]
      || '';
    var city = (t.match(/(北京|上海|广州|深圳|杭州|成都|南京|武汉|西安|苏州|东莞|佛山|珠海|厦门|长沙|合肥|宁波|青岛|天津|重庆|无锡|宁德|中山)/) || [])[1] || '';
    /* 岗位名后面常跟「（广州）」这类城市/序列补充，截掉才不会带进标题 */
    role = role.replace(/[（(【\[].*$/, '').replace(/[，,。;；].*$/, '').trim();
    return { company: company, role: role, city: city };
  }

